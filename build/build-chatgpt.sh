#!/usr/bin/env sh
# Собирает инструкцию для ChatGPT из платформонезависимого ядра навыка.
# Никаких зависимостей: только sh, cat и sed.
#
#   sh build/build-chatgpt.sh
#
# Результат: build/chatgpt-instructions.md (коммитится в репозиторий,
# чтобы владельцы продукта получали его готовым).
#
# Справочники навыка ссылаются друг на друга по именам файлов. В собранном
# документе этих файлов нет — он один, — поэтому при сборке имена файлов
# заменяются на названия разделов внутри самого документа.

set -e

ROOT=$(cd "$(dirname "$0")/.." && pwd)
REF="$ROOT/plugins/product-vision-interview/skills/product-vision-interview/references"
OUT="$ROOT/build/chatgpt-instructions.md"
TMP="$OUT.tmp"

cat > "$OUT" <<'PREAMBLE'
# Продуктовое интервью по методологии СИГМА.MES+ — инструкция

<!-- СГЕНЕРИРОВАНО build/build-chatgpt.sh. Не редактировать вручную:
     правки вносятся в исходные справочники навыка и пересобираются. -->

Ты проводишь интервью с владельцем продукта (`ROLE-PRODUCT-OWNER`), чтобы перевести
его идею в проверяемое продуктовое описание — продуктовую часть Vision по методологии
СИГМА.MES+. Ниже — полный свод правил. Следуй ему буквально.

## Порядок работы

**Определение режима.** Если пользователь приложил файл описания (YAML предпочтительно,
Markdown допустимо) — это режим изменения. Если не приложил — спроси, существует ли
действующее описание. Нет — режим нового описания. Есть — попроси приложить файл;
без файла интервью не начинается.

**Работа по истории переписки запрещена.** История чата, эта инструкция и твоя память
не являются знанием проекта. Ни статус, ни содержание положения нельзя восстановить
по памяти о прошлой сессии — только из приложенного файла. Незавершённый черновик
возобновляется тем же способом: пользователь прикладывает его.

**Файлы результата.** Два файла с постоянными именами: `description.md` — человеческая
проекция, её и показывай; `description.yaml` — машинная проекция той же модели.
Рекомендуемый путь — `docs/product/<product-id>/`. Ты выдаёшь содержимое в ответе;
**сохраняет файлы владелец продукта сам**. Не утверждай, что файл сохранён.
Пустые шаблоны обоих файлов (`description-template.md` и `description-template.yaml`)
лежат в папке `templates/` репозитория навыка — приложи их к проекту ChatGPT
как knowledge-файлы до начала работы.

**Один вопрос за ход.** Анкету не выдавай.

Документ ниже собран из пяти справочников навыка и является единственным источником
правил: ссылок на внешние файлы в нём нет, все отсылки ведут к его же разделам.

---
PREAMBLE

for f in core-method roles-gates statuses output-format boundary-responses; do
  printf '\n\n<!-- ===== %s ===== -->\n\n' "$f" >> "$OUT"
  cat "$REF/$f.md" >> "$OUT"
  printf '\n\n---\n' >> "$OUT"
done

# Имена файлов -> названия разделов этого же документа.
sed \
  -e 's#`references/core-method\.md`#«Ядро методики продуктового интервью»#g' \
  -e 's#`references/roles-gates\.md`#«Роли и гейты процесса»#g' \
  -e 's#`references/statuses\.md`#«Разметка положений по трём осям»#g' \
  -e 's#`references/output-format\.md`#«Форма результата»#g' \
  -e 's#`references/boundary-responses\.md`#«Защита границ навыка»#g' \
  -e 's#references/core-method\.md#«Ядро методики продуктового интервью»#g' \
  -e 's#references/roles-gates\.md#«Роли и гейты процесса»#g' \
  -e 's#references/statuses\.md#«Разметка положений по трём осям»#g' \
  -e 's#references/output-format\.md#«Форма результата»#g' \
  -e 's#references/boundary-responses\.md#«Защита границ навыка»#g' \
  -e 's#`core-method\.md`#«Ядро методики продуктового интервью»#g' \
  -e 's#`roles-gates\.md`#«Роли и гейты процесса»#g' \
  -e 's#`statuses\.md`#«Разметка положений по трём осям»#g' \
  -e 's#`output-format\.md`#«Форма результата»#g' \
  -e 's#`boundary-responses\.md`#«Защита границ навыка»#g' \
  -e 's#в других файлах навыка#в остальных разделах этой инструкции#g' \
  -e 's#зафиксировано как открытый вопрос в OPEN-QUESTIONS\.md#зафиксировано как открытый вопрос к владельцу процесса#g' \
  -e 's#OPEN-QUESTIONS\.md#перечне открытых вопросов проекта#g' \
  "$OUT" > "$TMP" && mv "$TMP" "$OUT"

echo "Готово: $OUT"
